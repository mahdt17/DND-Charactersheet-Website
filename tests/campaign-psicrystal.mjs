import assert from 'node:assert/strict';
import {createArchivistCampaign,advanceArchivistCampaign,campaignRest,campaignSkillBonus,advanceCampaignTime} from '../src/lib/archivistCampaign.js';
import {psicrystalProfile,activatePsicrystal,changePsicrystalHP,movePsicrystal,manifestWithPsicrystal,deliverPsicrystalTouch} from '../src/lib/campaignPsicrystal.js';
import {learnCampaignPower} from '../src/lib/campaignPsionics.js';
let c=createArchivistCampaign();
assert.equal(psicrystalProfile(c).maxHP,11);
assert.throws(()=>activatePsicrystal(c,'flight'),/level/);
c=movePsicrystal(c,0);assert.equal(campaignSkillBonus(c,'Perception'),2);
c=activatePsicrystal(c,'legs');assert.equal(psicrystalProfile(c).speed,30);
c=advanceCampaignTime(c,1440);assert.equal(psicrystalProfile(c).speed,0);
c=changePsicrystalHP(c,100,{evasion:true,saveSucceeded:true});assert.equal(psicrystalProfile(c).currentHP,11);
c=changePsicrystalHP(c,30,{evasion:true});assert.equal(psicrystalProfile(c).currentHP,0);assert.equal(campaignSkillBonus(c,'Arcana'),0);
assert.throws(()=>activatePsicrystal(c,'legs'),/living/);
c=createArchivistCampaign();for(let i=0;i<14;i++)c=advanceArchivistCampaign(c,{kind:'psion'});
assert.equal(psicrystalProfile(c).level,15);assert.equal(psicrystalProfile(c).powerResistance,20);
c=activatePsicrystal(c,'sight');assert.throws(()=>activatePsicrystal(c,'sight'),/used/);
c=campaignRest(c,'long');c=activatePsicrystal(c,'sight');
c=movePsicrystal(c,0);c=manifestWithPsicrystal(c,'inertial-armor',{mode:'share'});assert(psicrystalProfile(c).sharedPowers['inertial-armor']);
c=movePsicrystal(c,6);assert.deepEqual(psicrystalProfile(c).sharedPowers,{});
c=movePsicrystal(c,0);c=learnCampaignPower(c,{name:'Test Touch',level:1,range:'Touch',minutes:1});
const id=c.archivistCampaign.knownPowers[0].id;
c=manifestWithPsicrystal(c,id,{mode:'touch'});assert(psicrystalProfile(c).pendingTouch);
c=deliverPsicrystalTouch(c);assert.equal(psicrystalProfile(c).pendingTouch,null);
c=movePsicrystal(c,5281);assert.throws(()=>manifestWithPsicrystal(c,id,{mode:'channel'}),/mile/);
console.log('PASS Psicrystal life, range, level gates, evasion, daily recovery, shared and touch powers');
