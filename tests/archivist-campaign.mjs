import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
assert(existsSync('src/lib/archivistCampaign.js'),'Campaign class rules must exist');
const C=await import('../src/lib/archivistCampaign.js');
const D=await import('../src/data/archivistCampaign.js');
let c=C.createArchivistCampaign('Darkdonte');
assert.equal(c.level,5);assert.deepEqual(c.classLevels.map(r=>r.level),[4,1]);
assert.deepEqual(c.abilities,{str:10,dex:10,con:10,int:15,wis:13,cha:16});
assert.equal(C.campaignProfile(c).ppMax,3);assert.equal(C.campaignProfile(c).darkMax,4);
assert.equal(C.campaignProfile(c).maxSpellLevel,2);assert.equal(C.campaignProfile(c).growthAllowance,8);
assert.equal(C.campaignProfile({...c,ruleset:'3.5'}).active,false);
assert.equal(C.campaignProfile({...c,classLevels:[{name:'Archivist',level:4,edition:'3.5',definition:{name:'Archivist',catalogId:'dndtools:classes/archivist-74',edition:'3.5'}}]}).active,false);
assert.throws(()=>C.useCampaignPower({...c,powerPointsUsed:3},'mindlink'),/points/i);
c=C.useCampaignPower(c,'mindlink');assert.equal(c.powerPointsUsed,1);
for(let level=6;level<=20;level++){
 c=C.advanceArchivistCampaign(c);
 const p=C.campaignProfile(c);
 assert.equal(c.level,level);assert.equal(p.archivist,level-2);assert.equal(p.psion,1);assert.equal(p.thrallherd,1);
 assert.equal(p.ppMax,3);assert.equal(c.powerPointsUsed,1,'leveling never restores PP');
 assert.equal(p.darkMax,3+Math.floor(p.archivist/3));assert.equal(p.maxSpellLevel,Math.min(9,Math.ceil(p.archivist/2)));
 assert.equal(p.score,level+4);assert.equal(p.thrallLevel,Math.min(level-1,D.followerTable[level+4].thrall));
 assert.deepEqual(p.believers,D.followerTable[level+4].believers);
}
assert.throws(()=>C.advanceArchivistCampaign(c),/20/);
assert.equal(C.campaignFeats(c).at(-1).name,'Cooperative Spell');
assert.equal(C.campaignCystSpells(c).length,10);
assert.equal(C.campaignProfile({...c,archivistCampaign:{...c.archivistCampaign,rulings:{ppMax:5,preparedLimit:3}}}).preparedLimit,3);
const cleric={id:'cure-wounds',index:'cure-wounds',catalogId:'2014:cure-wounds',edition:'2014',name:'Cure Wounds',level:1,classes:['Cleric'],ritual:false};
let starter=C.createArchivistCampaign('Book');
starter=C.acquireCampaignSpell(starter,cleric,{channel:'growth'});
assert.equal(C.campaignProfile(starter).growthRemaining,7);
assert.throws(()=>C.acquireCampaignSpell(starter,cleric,{channel:'growth'}),/already/i);
assert.throws(()=>C.acquireCampaignSpell(starter,{...cleric,name:'Other',catalogId:'2014:other',classes:['Wizard']},{channel:'growth'}),/Cleric/);
assert.throws(()=>C.acquireCampaignSpell(starter,{...cleric,level:3},{channel:'growth'}),/level/i);
assert.throws(()=>C.acquireCampaignSpell(starter,{...cleric,catalogId:'2014:outside',name:'Outside'},{channel:'outside'}),/source|confirm/i);
const before=C.campaignProfile(starter).growthRemaining;
starter=C.acquireCampaignSpell(starter,{...cleric,catalogId:'2014:outside',name:'Outside',classes:['Wizard']},{channel:'outside',source:'DM-approved scroll',confirmed:true});
assert.equal(C.campaignProfile(starter).growthRemaining,before);
starter=C.prepareCampaignSpell(starter,cleric.catalogId,true);assert(starter.spells.find(s=>s.catalogId===cleric.catalogId).prepared);
starter=C.useDarkKnowledge(starter,'tactics',{check:25,target:'Undead'});
assert.equal(starter.archivistCampaign.darkUsed,1);assert.equal(starter.archivistCampaign.knowledgeEffect.bonus,2);
assert.throws(()=>C.useDarkKnowledge(starter,'foreknowledge',{check:25,target:'Undead'}),/level/i);
const saved=JSON.parse(JSON.stringify(starter));assert.deepEqual(C.campaignProfile(saved),C.campaignProfile(starter));
starter=C.castCampaignSpell(starter,cleric.catalogId,{slot:1});assert.equal(starter.slotsUsed[1],1);
assert.throws(()=>C.castCampaignSpell(starter,'missing',{slot:1}),/available/i);
assert.throws(()=>C.castCampaignSpell(starter,cleric.catalogId,{slot:3}),/slot/i);
let sixth=C.advanceArchivistCampaign(C.createArchivistCampaign());
sixth=C.addCampaignFollower(sixth,{name:'First thrall',kind:'thrall',level:5,quantity:1});
assert.equal(sixth.archivistCampaign.followers[0].arrivalHours,24);
assert.throws(()=>C.addCampaignFollower(sixth,{name:'Second thrall',kind:'thrall',level:5,quantity:1}),/limit/i);
assert.throws(()=>C.addCampaignFollower(sixth,{name:'Too many',kind:'believers',level:1,quantity:6}),/limit/i);
assert.equal(C.advanceCampaignTime(sixth,1440).archivistCampaign.followers[0].arrivalHours,0);
const cyst=D.cystSpells.find(s=>s.name==='Necrotic Cyst');
assert.throws(()=>C.castCampaignSpell(c,cyst.catalogId,{slot:7,chain:true,confirmed:true}),/range/i);
const chained=C.castCampaignSpell(c,cyst.catalogId,{slot:7,reach:true,chain:true,confirmed:true});
assert.equal(chained.slotsUsed[7],1);assert.equal(chained.archivistCampaign.lastCast.secondaryTargets,18);
const bless={...cleric,catalogId:'2014:bless',name:'Bless',concentration:true};
starter=C.acquireCampaignSpell(starter,bless);
starter=C.prepareCampaignSpell(starter,bless.catalogId,true);
starter=C.castCampaignSpell({...starter,concentration:'Old spell'},bless.catalogId,{slot:1});
assert.equal(starter.concentration,'Bless');
assert.equal(C.castCampaignSpell(starter,cleric.catalogId,{slot:1}).concentration,'Bless');
const ritual={...cleric,catalogId:'2014:detect-magic',name:'Detect Magic',concentration:true,ritual:true};
starter=C.acquireCampaignSpell(starter,ritual);
const ritualCast=C.castCampaignSpell(starter,ritual.catalogId,{ritual:true});
assert.equal(ritualCast.concentration,'Detect Magic');assert.deepEqual(ritualCast.slotsUsed,starter.slotsUsed);
console.log('PASS campaign progression 5–20, source isolation, spell ownership, acquisition channels, expenditure and follower roster');

