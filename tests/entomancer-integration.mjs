import assert from 'node:assert/strict';
import {make} from './entomancer.mjs';
import {characterResources,adjustResource,restResources} from '../src/lib/resources.js';
import {multiclassPools} from '../src/lib/multiclassCasting.js';
import {multiclassTrainingPlan} from '../src/lib/training.js';
import {entomancerClass} from '../src/data/entomancer.js';
import {populationId,entomancerProfile} from '../src/lib/entomancer.js';
let c=make(5);assert.equal(characterResources(c).find(r=>r.id===populationId)?.max,7,'Population must appear in Resource Tracker');
let custom={...make(1),ruleset:'custom',mechanics:'2014'};
assert.equal(characterResources(custom).find(r=>r.id===populationId)?.max,2,'Custom Entomancer exposes the same reserve');
custom={...custom,...adjustResource(custom,populationId,1)};
assert.equal(entomancerProfile(custom).remaining,1);
custom=JSON.parse(JSON.stringify(custom));
assert.equal(characterResources(custom).filter(r=>r.id===populationId).length,1);
assert.equal(characterResources(custom).find(r=>r.id===populationId).used,1);
assert.equal(entomancerProfile({...custom,...restResources(custom,'long',{fed:true})}).remaining,2);
c={...c,...adjustResource(c,populationId,3)};assert.equal(entomancerProfile(c).remaining,4);
c={...c,...restResources(c,'long',{fed:false})};assert.equal(entomancerProfile(c).remaining,4);
c={...c,...restResources(c,'long',{fed:true})};assert.equal(entomancerProfile(c).remaining,7);
const mixed={...make(),level:6,classLevels:[{catalogId:'2014:fighter',name:'Fighter',level:1,edition:'2014',definition:{name:'Fighter',edition:'2014'}},{catalogId:entomancerClass.catalogId,name:'Entomancer',level:5,edition:'2014',definition:entomancerClass}]};
assert(characterResources(mixed).some(r=>r.name==='Second Wind'));
assert.equal(multiclassTrainingPlan({ruleset:'2014',className:'Fighter'},entomancerClass).mode,'automatic');
const pools=multiclassPools({...mixed,classLevels:[...mixed.classLevels,{name:'Wizard',level:3,edition:'2014',definition:{name:'Wizard',edition:'2014'}}]},c=>c.className==='Entomancer'?entomancerProfile(c).slots:[0,4,3,2]);
assert.equal(pools.mode,'automatic');assert.equal(pools.casterLevel,5);
const removed={...c,className:'Fighter',classDefinition:{name:'Fighter',edition:'2014'}};
assert(!characterResources(removed).some(r=>r.id===populationId),'Removed class must not leave a working Population reserve');
console.log('PASS Entomancer tracker, canonical expenditure, fed rests, multiclass resources, training and pooled slots');

const {applyEntomancerAction}=await import('../src/lib/entomancerActions.js');
let armored=applyEntomancerAction(make(5),'bug-armor');
assert.equal(restResources(armored,'short').hp?.temp,0,'short rest removes expired armor temp HP');
let eating=applyEntomancerAction(make(18),'decompose',{target:'Lunch',size:'Large',distance:30});
assert.equal(restResources(eating,'short').hp?.current,77,'short rest preserves Corpse Eater healing');
let revived=make(17);revived.entomancer.effects={swarmForm:undefined};
assert.doesNotThrow(()=>applyEntomancerAction(revived,'advance-time',{rounds:1}));
let tiny=applyEntomancerAction(make(18),'decompose',{target:'Tiny corpse',size:'Tiny',distance:0});
assert.equal(tiny.entomancer.effects.decompose,undefined,'instant decomposition cannot be refunded again');
assert.equal(applyEntomancerAction(tiny,'advance-time',{rounds:1}).hp.current,77);
const imported=make(5,'Decomposers',{resources:[{id:'imported-pool',classResourceKey:populationId,name:'Population',max:99,used:3,manual:true,reset:'long'}]});
const importedPool=characterResources(imported).find(r=>r.classResourceKey===populationId);
assert.equal(importedPool.id,populationId);
assert.equal(importedPool.max,7);
assert.equal(importedPool.used,3);
assert.equal(importedPool.reset,'none');
const namedManual=make(5,'Decomposers',{resources:[{id:'manual',name:'Population',max:3,used:1}]});
assert(characterResources(namedManual).some(r=>r.id===populationId),'unrelated manual names cannot suppress the canonical reserve');
