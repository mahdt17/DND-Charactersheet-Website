import assert from 'node:assert/strict';
import {requirements} from '../src/lib/advancement.js';
import {catalog35} from '../src/lib/catalog35.js';
import {castingAdvancementPlan,castingAdvancementGrants} from '../src/lib/classIntegration.js';

const classes=await catalog35('classes');
const exact=id=>{
  const row=classes.find(item=>item.sourceId===id);
  assert(row,'missing class '+id);
  return row;
};
const wizard=exact('classes/wizard-22'),mystic=exact('classes/mystic-theurge-69');
const row=(definition,level)=>({catalogId:definition.catalogId,level,edition:'3.5',definition});
const character=(classLevels=[])=>({ruleset:'3.5',level:20,abilities:{int:18,wis:18,cha:18},classLevels,feats:[],skillRanks:{}});
const spell=(minimum,tradition)=>({kind:'spellcasting',minimum,tradition,text:`Ability to cast ${minimum}th-level ${tradition} spells`});
const status=(c,p)=>requirements({catalogId:'test:casting',edition:'3.5',prerequisites:[p]},c)[0].status;
const w5=character([row(wizard,5)]);
assert.equal(status(w5,spell(3,'arcane')),'met');
assert.equal(status(w5,spell(4,'arcane')),'unmet');
assert.equal(status(w5,spell(1,'divine')),'unmet');
assert.equal(status({...w5,abilities:{int:12,wis:18,cha:18}},spell(3,'arcane')),'unmet','ability access must gate spell level');
const unknown={...wizard,catalogId:'dndtools:classes/unknown-caster',sourceId:'classes/unknown-caster',id:'classes/unknown-caster',name:'Unknown Caster',castingAbility:'int',castingTraditions:[],progression:wizard.progression};
assert.equal(status(character([row(unknown,5)]),spell(3,'arcane')),'manual','unknown tradition stays manual');
const noSlots={...wizard,catalogId:'dndtools:classes/no-slots',sourceId:'classes/no-slots',id:'classes/no-slots',name:'No Slots',castingAbility:'int',castingTraditions:['arcane'],progression:[]};
assert.equal(status(character([row(noSlots,5)]),spell(3,'arcane')),'manual','reviewed tradition without slot progression stays manual');
const divine=exact('classes/cleric-91');
const dual=character([row(wizard,5),row(divine,5)]);
assert.equal(status(dual,spell(3,'arcane')),'met');
assert.equal(status(dual,spell(3,'divine')),'met');
const plan=castingAdvancementPlan(dual,mystic,1);
const picks=Object.fromEntries(plan.groups.map(group=>[group.id,group.kind==='arcane'?wizard.catalogId:divine.catalogId]));
const grants=castingAdvancementGrants(mystic,1,plan,picks);
const advanced={...dual,classLevels:[...dual.classLevels,row(mystic,1)],castingAdvancements:grants};
assert.equal(status(advanced,spell(4,'arcane')),'met','reviewed prestige advancement must lend spell progression');
assert.equal(status(advanced,spell(4,'divine')),'met','dual advancement must lend both tracks');
assert.equal(status({...dual,casterLevel:20,slotOverride:[0,9,9,9,9]},spell(3,'arcane')),'unmet');
assert.equal(status({...advanced,castingAdvancements:advanced.castingAdvancements.map(e=>({...e,amount:99}))},spell(3,'arcane')),'unmet','malformed amounts cannot invent advancement');
assert.equal(status({...advanced,castingAdvancements:advanced.castingAdvancements.map(e=>({...e,sourceClassLevel:20}))},spell(3,'arcane')),'unmet','future source levels cannot grant casting');
const staleSource='dndtools:classes/unreviewed-prestige';
assert.notEqual(status({...advanced,classLevels:advanced.classLevels.map(r=>r.catalogId===mystic.catalogId?{...r,catalogId:staleSource}:r),castingAdvancements:advanced.castingAdvancements.map(e=>({...e,sourceClassId:staleSource,id:e.id.replace(mystic.catalogId,staleSource)}))},spell(3,'arcane')),'met','mismatched advancement-source definition cannot lend levels');
assert.notEqual(status({...advanced,classLevels:advanced.classLevels.map(r=>r.catalogId===mystic.catalogId?{...r,definition:{...r.definition,sourceId:'classes/unreviewed-prestige'}}:r)},spell(3,'arcane')),'met','conflicting advancement-source identities cannot lend levels');
assert.equal(status(character([row(wizard,Infinity)]),spell(9,'arcane')),'manual','invalid class levels cannot qualify');
const suppressed={...wizard,featureSuppressions:[{name:'Spells'}]};
assert.equal(status(character([row({...wizard,progression:[],tables:[],advancement:[]},5)]),spell(3,'arcane')),'manual','known casting with missing progression remains unresolved');
assert.equal(status(character([row(suppressed,5)]),spell(3,'arcane')),'manual','suppressed casting must not qualify');
const archivist=exact('classes/archivist-74');
assert.equal(status({...character([row(archivist,5)]),abilities:{int:12,wis:20}},spell(3,'divine')),'unmet','Archivist uses Intelligence for spell access, not Wisdom bonus slots');
assert.equal(status({...character([row(exact('classes/favored-soul-7'),6)]),abilities:{wis:20,cha:12}},spell(3,'divine')),'unmet','Favored Soul uses Charisma for access, not its Wisdom save DC');
assert.equal(status({...character([row(exact('classes/spirit-shaman-9'),5)]),abilities:{wis:12,cha:20}},spell(3,'divine')),'unmet','Spirit Shaman uses Wisdom for access, not its Charisma save DC');
const record={catalogId:'test:confirmation',edition:'3.5',prerequisites:[spell(3,'arcane'),spell(4,'arcane')]};
const unknownChecks=requirements(record,character([row(unknown,7)]));
assert.notEqual(unknownChecks[0].id,unknownChecks[1].id);
assert.equal(requirements(record,character([row(unknown,7)]),{[unknownChecks[0].id]:true})[1].status,'manual');
const {castingPrerequisiteCoverage35}=await import('../scripts/audit_casting_prerequisites35.mjs');
const coverage=castingPrerequisiteCoverage35(classes);
assert.equal(coverage.uniqueAffectedCount,154);
assert.deepEqual(coverage.manualContext.map(r=>r.sourceId),['classes/ardent-dilettante-685','classes/ruathar-744']);
assert(coverage.supported.some(r=>r.sourceId===mystic.sourceId));
for(const minimum of [-1,10,1.5,'3'])assert.equal(status(w5,spell(minimum,'arcane')),'manual');
for(const id of ['classes/ruathar-744','classes/ardent-dilettante-685']){
  const checks=requirements(exact(id),w5);
  assert(checks.filter(c=>c.label==='Spells').every(c=>c.status==='manual'),'staged/cross-clause alternatives must remain manual: '+id);
}
console.log('Casting prerequisite tradition, ability, advancement and lifecycle regressions passed.');