import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {chromium} from 'playwright';
import {createServer} from 'vite';
import {normalizeCatalogRecord} from '../src/lib/catalog.js';

const raw=JSON.parse(await fs.readFile('public/catalogs/dndtools/classes.json','utf8'));
const cleric=normalizeCatalogRecord(raw.find(r=>r.name==='Cleric'&&!r.prestige),'dndtools','classes');
const character={name:'Patron migration browser',ruleset:'3.5',mechanics:'3.5',level:5,className:'Cleric',classDefinition:cleric,classLevels:[{catalogId:cleric.catalogId,name:'Cleric',definition:cleric,edition:'3.5',level:5}],race:'Human',alignment:'lawful evil',hitDie:'d8',hp:{current:20,max:20,temp:0},abilities:{str:10,dex:10,con:10,int:10,wis:16,cha:10},inventory:[],actions:[],spells:[],feats:[],resources:[],featureChoices:{},conditions:[],legacyCastingChoices:{[cleric.catalogId]:{deity:'Hextor',domains:['Evil','War']}}};
await fs.mkdir('test-results',{recursive:true});
const importPath='test-results/patron35-import.json';await fs.writeFile(importPath,JSON.stringify(character));
const server=await createServer({server:{host:'127.0.0.1',port:0}});await server.listen();
let browser;
try{
 browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE_PATH||undefined});
 const page=await browser.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(server.resolvedUrls.local[0]);await page.getByRole('button',{name:'Explore the demo'}).click();
 await page.locator('input[type="file"][accept*="json"]').setInputFiles(importPath);
 await page.locator('.sheet-identity').filter({hasText:character.name}).waitFor();
 await page.getByRole('tab',{name:'Traits',exact:true}).click();
 const patron=()=>page.getByRole('textbox',{name:'Patron deity',exact:true});
 await patron().waitFor({timeout:5000});
 assert.equal(await patron().inputValue(),'Hextor','old Cleric deity migrates into the shared identity');
 await patron().fill('Malar');await page.getByRole('button',{name:'Save patron',exact:true}).click();
 await page.getByRole('tab',{name:'Spells',exact:true}).click();
 await page.getByRole('button',{name:'Manage spells',exact:true}).click();
 assert.equal(await page.getByLabel('Cleric deity',{exact:true}).inputValue(),'Malar','unsupported domain identity must remain visible');
 await page.getByText(/Domain rules for this deity need source review\./).waitFor();
 await page.getByLabel('Cleric deity',{exact:true}).selectOption({label:'Pelor'});
 await page.getByRole('tab',{name:'Traits',exact:true}).click();
 assert.equal(await patron().inputValue(),'Pelor','existing Cleric selector updates the same patron');
 await page.getByRole('button',{name:'All characters',exact:true}).click();
 await page.locator('.character-card').filter({hasText:character.name}).getByRole('button',{name:'Open character'}).click();
 await page.getByRole('tab',{name:'Traits',exact:true}).click();
 assert.equal(await patron().inputValue(),'Pelor','patron survives save and reopen');
 await patron().fill('pelor');await page.getByRole('button',{name:'Save patron',exact:true}).click();
 await page.getByRole('tab',{name:'Spells',exact:true}).click();
 await page.getByRole('button',{name:'Manage spells',exact:true}).click();
 assert.equal(await page.getByLabel('Cleric deity',{exact:true}).inputValue(),'Pelor','case-insensitive patron identity selects the canonical domain option');
 assert.equal(await page.getByText(/Domain rules for this deity need source review\./).count(),0);
 await page.getByRole('tab',{name:'Traits',exact:true}).click();
 await patron().fill('');await page.getByRole('button',{name:'Save patron',exact:true}).click();
 await page.getByRole('button',{name:'All characters',exact:true}).click();
 await page.locator('.character-card').filter({hasText:character.name}).getByRole('button',{name:'Open character'}).click();
 await page.getByRole('tab',{name:'Traits',exact:true}).click();
 assert.equal(await patron().inputValue(),'','explicit no-patron choice must not revive old class values');
 assert.deepEqual(errors,[]);
 console.log('PASS patron identity: old save, both editing surfaces, unknown domain rules, persistence and clearing');
}finally{if(browser)await browser.close();await server.close();}
