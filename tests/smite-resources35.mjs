import assert from 'node:assert/strict';
import fs from 'node:fs';
import {normalizeCatalogRecord} from '../src/lib/catalog.js';
import {reconcileClassGrants,removeClassProgression} from '../src/lib/classIntegration.js';
import {adjustResource,restResources} from '../src/lib/resources.js';

const catalog=JSON.parse(fs.readFileSync('public/catalogs/dndtools/classes.json','utf8'));
const row=(id,level)=>{const definition=normalizeCatalogRecord(catalog.find(r=>r.id===id),'dndtools','classes');return {catalogId:definition.catalogId,name:definition.name,edition:'3.5',level,definition};};
const paladin=n=>row('classes/paladin-95',n),argent=n=>row('classes/argent-fist-468',n),monk=n=>row('classes/monk-94',n);
const make=(classLevels,extra={})=>reconcileClassGrants({ruleset:'3.5',classLevels,abilities:{cha:16},...extra});
const smites=c=>c.resources.filter(r=>r.name==='Smite Evil');
const native=c=>smites(c).find(r=>r.sourceClassId==='dndtools:classes/paladin-95');
for(const [level,uses] of [[1,1],[4,1],[5,2],[9,2],[10,3],[14,3],[15,4],[19,4],[20,5]])assert.equal(native(make([paladin(level)])).max,uses,'native daily-use milestones remain unchanged');
for(const [level,uses,damage] of [[1,2,8],[3,2,10],[4,3,11],[8,3,15],[9,4,16],[10,4,17]]){
 const c=make([paladin(5),monk(2),argent(level)]);
 assert.equal(smites(c).length,1,'Argent Fist advances the existing smite pool');
 assert.equal(native(c).max,uses,'extra uses come only from levels four and nine');
 assert.equal(native(c).smite35?.damageBonus,damage,'damage adds Paladin, Monk and Argent Fist levels separately');
 assert.equal(native(c).smite35.attackBonus,3,'Charisma affects the attack, not damage');
}
const base=make([paladin(5)]),oldArgent=make([argent(9)]).resources.find(r=>r.name==='Smite Evil');
let migrated=make([paladin(5),monk(2),argent(9)],{resources:[{...native(base),used:2},{...oldArgent,used:1}]});
assert.equal(native(migrated).used,3,'both legacy source counters contribute their spending exactly once');
assert.deepEqual(reconcileClassGrants(migrated),migrated,'reconciliation must not migrate expenditure twice');
assert.equal(native(reconcileClassGrants(JSON.parse(JSON.stringify(migrated)))).used,3);
migrated=reconcileClassGrants({...migrated,...adjustResource(migrated,native(migrated).id,1)});
assert.equal(native(migrated).used,4);
assert.throws(()=>adjustResource(migrated,native(migrated).id,1),/Not enough/);
const lowered=reconcileClassGrants({...migrated,classLevels:[paladin(5),monk(2),argent(1)]});
assert.equal(native(lowered).max,2);assert.equal(native(lowered).used,4,'lost extra uses do not refund expenditure');
const removed=removeClassProgression(migrated,argent(9).catalogId);
assert.equal(native(removed).max,2);assert.equal(native(removed).used,4);
assert.equal(native(removed).smite35.damageBonus,5,'Monk contributes only while Ascetic Knight is present');
const noNative=removeClassProgression(migrated,paladin(5).catalogId);
const held=smites(noNative)[0];
assert.equal(held?.max,0,'Argent additional uses do not become an independent smite');
assert.equal(held?.used,4,'removing the native owner holds expenditure on the surviving contribution');
assert.equal(held?.smite35.resolved,false);
assert.throws(()=>adjustResource(noNative,held.id,1),/Not enough/);
assert.deepEqual(reconcileClassGrants(noNative),noNative);
assert.equal(smites(reconcileClassGrants({...noNative,...restResources(noNative,'short')}))[0].used,4);
assert.equal(smites(reconcileClassGrants({...noNative,...restResources(noNative,'long')}))[0].used,0,'daily recovery also resets held expenditure');
const ownerBack=reconcileClassGrants({...noNative,classLevels:[paladin(5),monk(2),argent(9)]});
assert.equal(native(ownerBack).used,4,'restoring the native owner cannot refund uses');
const lowWithoutOwner=removeClassProgression(lowered,paladin(5).catalogId);
assert.equal(smites(lowWithoutOwner)[0]?.used,4,'expenditure survives even below the extra-use milestone');
assert.equal(smites(lowWithoutOwner)[0]?.max,0);
assert.deepEqual(reconcileClassGrants(lowWithoutOwner),lowWithoutOwner);
assert.equal(native(reconcileClassGrants({...migrated,...restResources(migrated,'short')})).used,4);
assert.equal(native(reconcileClassGrants({...migrated,...restResources(migrated,'long')})).used,0);
assert.equal(native(make([paladin(5),argent(4)],{abilityBonuses:{cha:4}})).smite35.attackBonus,5);
assert.equal(native(make([paladin(5),argent(4)],{abilities:{cha:8}})).smite35.attackBonus,0);
const variant=monk(2);variant.catalogId='dndtools:classes/monk-66';variant.definition={...variant.definition,id:'classes/monk-66',sourceId:'classes/monk-66',catalogId:variant.catalogId,index:'classes/monk-66'};
assert.equal(native(make([paladin(5),variant,argent(4)])).smite35.damageBonus,null,'unreviewed Monk source cannot silently count or disappear from damage proof');
const mismatch=argent(4);mismatch.definition={...mismatch.definition,sourceId:'classes/unreviewed-argent'};
assert.equal(native(make([paladin(5),mismatch])).smite35,undefined,'conflicting source identities cannot activate stacking');
assert.equal(native(make([paladin(5),argent(4),argent(4)])).smite35,undefined,'duplicate rows cannot inflate smite progression');
const other={catalogId:'test:other-smite',name:'Other smite',edition:'3.5',level:1,definition:{name:'Other smite',edition:'3.5',levelGrants:[{level:1,name:'Smite Evil',description:'Once per day, smite an evil enemy.'}]}};
assert.equal(native(make([paladin(5),argent(4),other])).smite35,undefined,'multiple possible native smite owners require a reviewed target');
const independent=make([paladin(5),argent(4),row('classes/divine-champion-661',3)]);
assert.equal(independent.resources.find(r=>r.name==='Smite Infidel')?.max,1,'restricted independent smites remain separate');
const manual={...native(base),max:7,used:3,manual:true,reset:'none'};
const custom=make([paladin(5),argent(4)],{resources:[manual]});
assert.equal(native(custom).max,7);assert.equal(native(custom).used,3);assert.equal(native(custom).reset,'none','manual counter settings remain authoritative');
const manualArgent={...oldArgent,max:7,used:3,manual:true,reset:'none'};
const manualLowered=make([paladin(5),argent(1)],{resources:[manualArgent]});
assert.equal(manualLowered.resources.find(r=>r.id===manualArgent.id)?.max,7,'manual counters survive loss of an automatic unlock');
const manualRemoved=removeClassProgression(custom,paladin(5).catalogId);
assert.equal(manualRemoved.resources.find(r=>r.id===manual.id)?.used,3,'a custom counter survives removing its former source');
console.log('PASS smite resources: separate damage/use advancement, source ownership, legacy spending migration, lifecycle, ability changes and unresolved sources');
