import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {normalizeCatalogRecord} from '../src/lib/catalog.js';
import {reconcileClassGrants,removeClassProgression} from '../src/lib/classIntegration.js';
import {adjustResource,restResources} from '../src/lib/resources.js';

const catalog=JSON.parse(await fs.readFile('public/catalogs/dndtools/classes.json','utf8')).map(r=>normalizeCatalogRecord(r,'dndtools','classes'));
const row=(id,level)=>{const definition=catalog.find(r=>r.sourceId===id);assert(definition,id);return {catalogId:definition.catalogId,name:definition.name,definition,edition:'3.5',level};};
const paladin=n=>row('classes/paladin-95',n),champion=n=>row('classes/divine-champion-661',n);
const make=(classLevels,cha=16,extra={})=>reconcileClassGrants({ruleset:'3.5',classLevels,abilities:{cha},...extra});
const pool=(c,id='classes/paladin-95',name='Lay on Hands')=>c.resources.find(r=>r.sourceClassId==='dndtools:'+id&&r.name===name);
assert.equal(pool(make([paladin(1)])),undefined,'Paladin healing unlocks at second level');
for(const level of [2,5,10,20])assert.equal(pool(make([paladin(level)])).max,level*3,'Paladin level times positive Charisma modifier');
assert.equal(pool(make([paladin(5)],11)).max,0,'Charisma below12 has no healing capacity');
assert.equal(pool(make([paladin(5)],8)).max,0,'negative Charisma never creates negative healing');
assert.equal(pool(make([paladin(5)],12,{abilityBonuses:{cha:4}})).max,15,'recorded ability bonuses affect the shared resource formula');
let c=make([paladin(5),champion(3)]);
assert.equal(pool(c).max,15);assert.equal(pool(c,'classes/divine-champion-661').max,9,'restricted champion healing remains separate');
assert.equal(c.resources.filter(r=>r.name==='Lay on Hands').length,2);
const id=pool(c).id,championId=pool(c,'classes/divine-champion-661').id;
c=reconcileClassGrants({...c,...adjustResource(c,id,12)});
assert.equal(pool(c).used,12);assert.equal(pool(c,'classes/divine-champion-661').used,0,'spending one pool does not spend the other');
let lowered=reconcileClassGrants({...c,abilities:{cha:12}});
assert.equal(pool(lowered).max,5);assert.equal(pool(lowered).used,12,'lower capacity cannot refund healing expenditure');
lowered=reconcileClassGrants({...lowered,abilities:{cha:10}});
assert.equal(pool(lowered).max,0);assert.equal(pool(lowered).used,12,'zero capacity retains saved expenditure');
let reopened=reconcileClassGrants({...JSON.parse(JSON.stringify(lowered)),abilities:{cha:16}});
assert.equal(pool(reopened).max,15);assert.equal(pool(reopened).used,12,'restoring Charisma does not restore spent healing');
assert.throws(()=>adjustResource(reopened,id,4),/Not enough/);
reopened=reconcileClassGrants({...reopened,...adjustResource(reopened,championId,4)});
assert.equal(pool(reopened,'classes/divine-champion-661').used,4);
assert.equal(pool(reconcileClassGrants({...reopened,...restResources(reopened,'short')})).used,12,'short rest does not restore daily healing');
const rested=reconcileClassGrants({...reopened,...restResources(reopened,'long')});
assert.equal(pool(rested).used,0);assert.equal(pool(rested,'classes/divine-champion-661').used,0);
const removed=removeClassProgression(reopened,paladin(5).catalogId);
assert.equal(pool(removed),undefined);assert.equal(pool(removed,'classes/divine-champion-661').used,4);
const vitality=make([row('classes/dragon-shaman-101',6)],12,{abilityBonuses:{cha:4}});
assert.equal(pool(vitality,'classes/dragon-shaman-101','Touch of Vitality').max,36,'existing healing formula shares effective ability calculation');
const smite=make([paladin(10)]);const smiteId=smite.resources.find(r=>r.name==='Smite Evil').id;
const spent={...smite,...adjustResource(smite,smiteId,3)};
const reduced=reconcileClassGrants({...spent,classLevels:[paladin(1)]});
assert.equal(reduced.resources.find(r=>r.id===smiteId).used,3,'shared reconciliation preserves spent smites when the maximum drops');
console.log('PASS healing resources: Paladin unlock/formula, restricted source pools, ability changes, no spending refunds, save/reopen, rests and removal');
