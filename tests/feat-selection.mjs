import assert from 'node:assert/strict';
import fs from 'node:fs';
import {validFeatSelection} from '../src/lib/featSelection.js';
import {requirements,qualified} from '../src/lib/advancement.js';
const revised=JSON.parse(fs.readFileSync('src/data/srd2024.json'));
const grappler={...revised.feats.find(f=>f.name==='Grappler'),edition:'2024'};
const c={ruleset:'2024',level:4,className:'Fighter',abilities:{str:12,dex:13},feats:[]};
assert(validFeatSelection(grappler,c));
assert(!validFeatSelection(grappler,{...c,level:3}));
assert(!validFeatSelection(grappler,{...c,abilities:{str:12,dex:12}}));
assert(validFeatSelection(grappler,{...c,abilities:{str:12,dex:12},abilityBonuses:{str:1}}));
assert(!validFeatSelection(grappler,{...c,ruleset:'2014'}));
assert(!validFeatSelection(grappler,{...c,feats:[{...grappler,catalogId:'2024:grappler',id:'instance'}]}));
assert(!validFeatSelection({...grappler,integrityIssues:['broken']},c));
assert(!validFeatSelection(null,c));assert(validFeatSelection(null,c,{required:false}));
const original=structuredClone(grappler);requirements(grappler,c);requirements(grappler,c);assert.deepEqual(grappler,original);
const boon={...revised.feats.find(f=>f.name==='Boon of Spell Recall'),edition:'2024'};
let checks=requirements(boon,{...c,level:19});assert.deepEqual(checks.map(x=>x.status),['met','manual']);
const confirmations=Object.fromEntries(checks.map(x=>[x.id,true]));
assert(validFeatSelection({...boon,prerequisiteConfirmations:confirmations},{...c,level:19}));
assert(!validFeatSelection({...boon,prerequisiteConfirmations:confirmations},c),'confirmation cannot override a known unmet level');
assert(validFeatSelection({...boon,prerequisiteConfirmations:confirmations},{...c,level:19,classLevels:[{name:'Fighter',level:4},{name:'Wizard',level:15}]}));
const custom={id:'custom',name:'Table feat',source:'Homebrew',edition:'2024'};
assert(!validFeatSelection(custom,c));assert(validFeatSelection({...custom,eligibilityReviewed:true},c));
const self={index:'self',edition:'2024',prerequisites:[{kind:'feat',text:'Self'}],name:'Self'};
assert(!validFeatSelection(self,c),'a selected feat cannot satisfy its own prerequisites');
assert(!qualified(requirements({prerequisites:{unknown:{value:2}}},c)));
assert(qualified(requirements({prerequisites:{kind:'ability',ability:'Dexterity',minimum:13}},c)));
const array={prerequisites:[{kind:'ability',ability:'Dexterity',minimum:13}],prerequisite_options:grappler.prerequisite_options};
requirements(array,c);requirements(array,c);assert.equal(array.prerequisites.length,1);
console.log('PASS feat eligibility: total level, alternate abilities, bonuses, edition, duplicates, source integrity, explicit manual review and immutable prerequisites');
